drop policy if exists "jianbox admins read release objects" on storage.objects;
create policy "jianbox admins read release objects"
  on storage.objects for select to authenticated
  using (bucket_id = 'app-releases' and (select private.jianbox_is_admin()));

drop policy if exists "jianbox admins upload release objects" on storage.objects;
create policy "jianbox admins upload release objects"
  on storage.objects for insert to authenticated
  with check (bucket_id = 'app-releases' and (select private.jianbox_is_admin()));

drop policy if exists "jianbox admins update release objects" on storage.objects;
create policy "jianbox admins update release objects"
  on storage.objects for update to authenticated
  using (bucket_id = 'app-releases' and (select private.jianbox_is_admin()))
  with check (bucket_id = 'app-releases' and (select private.jianbox_is_admin()));

drop policy if exists "jianbox admins delete release objects" on storage.objects;
create policy "jianbox admins delete release objects"
  on storage.objects for delete to authenticated
  using (bucket_id = 'app-releases' and (select private.jianbox_is_admin()));
